"""`discover` and live `validate`: read Home Assistant entities and suggest / check a mapping.

Both only READ from Home Assistant.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from typing import Any

from villa_agent.site import NAME_PART, Site, device_types


@dataclass(frozen=True)
class Entity:
    entity_id: str
    domain: str
    device_class: str | None
    unit: str | None
    friendly_name: str

    @classmethod
    def from_state(cls, state: dict[str, Any]) -> Entity | None:
        eid = state.get("entity_id")
        if not isinstance(eid, str) or "." not in eid:
            return None
        attrs = state.get("attributes") or {}
        return cls(
            entity_id=eid,
            domain=eid.split(".", 1)[0],
            device_class=attrs.get("device_class"),
            unit=attrs.get("unit_of_measurement"),
            friendly_name=str(attrs.get("friendly_name") or eid),
        )

    @property
    def object_id(self) -> str:
        return self.entity_id.split(".", 1)[1]


def entities_from_states(states: list[dict[str, Any]]) -> list[Entity]:
    out = [e for s in states if isinstance(s, dict) and (e := Entity.from_state(s))]
    return sorted(out, key=lambda e: e.entity_id)


# ---------------------------------------------------------------- suggestion logic

_PLUG_WORDS = ("plug", "priza", "socket", "outlet", "prize")
_LIGHT_WORDS = ("light", "lamp", "fos", "fota", "led", "lampa")
_BACKUP_WORDS = ("4g", "lte", "backup", "failover")

# Words removed from an entity's object_id to guess the room/name part.
_NOISE_WORDS = {
    "sensor", "temperature", "temp", "humidity", "hum", "battery", "bat", "level",
    "moisture", "leak", "water", "door", "window", "contact", "opening", "smoke",
    "noise", "sound", "pressure", "climate", "ac", "aircon", "light", "lamp", "switch",
    "plug", "socket", "outlet", "lock", "state", "status", "binary", "percent",
}  # fmt: skip


def suggest_type(e: Entity) -> str | None:
    name = f"{e.object_id} {e.friendly_name}".lower()
    dc = e.device_class
    if e.domain == "binary_sensor":
        if dc == "moisture":
            return "leak"
        if dc in ("door", "window", "garage_door", "opening"):
            return "door"
        if dc == "smoke":
            return "smoke"
        if any(w in name for w in _BACKUP_WORDS):
            return "internet_backup"
        return None
    if e.domain == "sensor":
        return {
            "temperature": "temp",
            "humidity": "humidity",
            "battery": "battery",
            "sound_pressure": "noise",
        }.get(dc or "")
    if e.domain == "climate":
        return "ac"
    if e.domain == "light":
        return "light"
    if e.domain == "switch":
        if any(w in name for w in _LIGHT_WORDS):
            return "light"
        if any(w in name for w in _PLUG_WORDS):
            return "plug"
        return None  # a switch could be anything (a pump, a boiler): do not guess
    if e.domain == "lock":
        return "lock"
    return None


def _name_part(e: Entity) -> str:
    words = [w for w in re.split(r"[^a-z0-9]+", e.object_id.lower()) if w]
    kept = [w for w in words if w not in _NOISE_WORDS] or words or ["device"]
    part = "_".join(kept)
    if not part[0].isalpha():
        part = "d_" + part
    return part if NAME_PART.fullmatch(part) else "device"


# Domains that describe people or places, not devices. Never listed in the draft file,
# which may end up in Git (names like "Maria's iPhone" are personal data).
PRIVATE_DOMAINS = frozenset(
    {"person", "device_tracker", "zone", "calendar", "notify", "tts", "conversation"}
)


def suggest_mapping(entities: list[Entity]) -> tuple[dict[str, Entity], list[Entity]]:
    """Return ({canonical: entity}, unmatched entities). Never maps power_main (do not guess)."""
    types = {t.name: t for t in device_types()}
    mapping: dict[str, Entity] = {}
    unmatched: list[Entity] = []
    for e in entities:
        if e.domain in PRIVATE_DOMAINS:
            continue
        tname = suggest_type(e)
        if tname is None:
            unmatched.append(e)
            continue
        t = types[tname]
        base = t.pattern if t.prefix is None else t.prefix + _name_part(e)
        canonical, n = base, 2
        while canonical in mapping:
            canonical = f"{base}_{n}"
            n += 1
        mapping[canonical] = e
    return mapping, unmatched


def render_draft(
    site_id: str, display_name: str, mapping: dict[str, Entity], unmatched: list[Entity]
) -> str:
    lines = [
        f"# DRAFT site mapping for {site_id}, generated by `python -m villa_agent discover`.",
        "# 1. Check every guess below, fix names, delete the devices you do not want.",
        "#    Names must look like the canonical list (leak_<room>, door_<name>, temp_<room> ...).",
        f"# 2. Rename this file to {site_id}.yaml",
        f"# 3. Run: python -m villa_agent validate sites/{site_id}.yaml --ha-url <your HA url>",
        "# NEVER put tokens or passwords in this file.",
        "",
        "schema_version: 1",
        f"site_id: {site_id}",
        # A JSON string is also a valid YAML string, and safely quotes ':' or '#'.
        f"display_name: {json.dumps(display_name, ensure_ascii=False)}",
        "timezone: Europe/Athens",
        "devices:",
    ]
    for canonical in sorted(mapping):
        e = mapping[canonical]
        info = ", ".join(x for x in (e.device_class, e.unit) if x)
        lines.append(f"  {canonical}:  # {e.friendly_name}" + (f" ({info})" if info else ""))
        lines.append(f"    entity_id: {e.entity_id}")
        lines.append(
            "    critical: " + ("true" if canonical.startswith(("leak_", "smoke_")) else "false")
        )
    lines.append("")
    lines.append("# power_main is never guessed. If you have a sensor that shows mains power,")
    lines.append("# add it by hand:")
    lines.append("#  power_main:")
    lines.append("#    entity_id: binary_sensor.<your_mains_sensor>")
    lines.append("#    critical: true")
    if unmatched:
        lines.append("")
        lines.append(f"# Not matched ({len(unmatched)} entities). Add by hand if needed:")
        for e in unmatched[:300]:
            info = ", ".join(x for x in (e.device_class, e.unit) if x)
            lines.append(f"#   {e.entity_id}  {e.friendly_name}" + (f" ({info})" if info else ""))
        if len(unmatched) > 300:
            lines.append(f"#   ... and {len(unmatched) - 300} more")
    return "\n".join(lines) + "\n"


def auto_site(
    site_id: str, display_name: str, entities: list[Entity], timezone: str = "Europe/Athens"
) -> dict[str, Any]:
    """A ready-to-use site mapping built from Home Assistant, with no human review.

    Used by the Home Assistant app when the villa has no site file yet. Every suggested
    device is checked on its own and skipped if it does not pass the schema, so one odd
    entity never blocks the villa. Commands stay off for every device (read-only).
    """
    from villa_agent.site import validate_data

    mapping, _ = suggest_mapping(entities)
    devices: dict[str, dict[str, Any]] = {}
    for canonical in sorted(mapping):
        dev = {
            "entity_id": mapping[canonical].entity_id,
            "critical": canonical.startswith(("leak_", "smoke_")),
        }
        trial = {
            "schema_version": 1,
            "site_id": site_id,
            "display_name": display_name,
            "timezone": timezone,
            "devices": {canonical: dev},
        }
        if not validate_data(trial):
            devices[canonical] = dev
    return {
        "schema_version": 1,
        "site_id": site_id,
        "display_name": display_name,
        "timezone": timezone,
        "devices": devices,
    }


# ---------------------------------------------------------------- live validation


def check_against_ha(site: Site, entities: list[Entity]) -> tuple[list[str], list[str]]:
    """Return (errors, warnings) comparing the site file with live Home Assistant entities."""
    by_id = {e.entity_id: e for e in entities}
    errors: list[str] = []
    warnings: list[str] = []
    for canonical, dev in sorted(site.devices.items()):
        e = by_id.get(dev.entity_id)
        if e is None:
            errors.append(f"{canonical}: entity '{dev.entity_id}' does not exist in Home Assistant")
            continue
        t = dev.type
        if e.domain not in t.domains:
            errors.append(
                f"{canonical}: entity '{dev.entity_id}' has domain '{e.domain}', "
                f"{t.pattern} needs {' or '.join(t.domains)}"
            )
            continue
        if t.device_classes and e.device_class and e.device_class not in t.device_classes:
            warnings.append(
                f"{canonical}: device_class is '{e.device_class}', expected "
                f"{' or '.join(t.device_classes)}"
            )
        if t.unit and e.unit and e.unit != t.unit:
            warnings.append(f"{canonical}: unit is '{e.unit}', expected '{t.unit}'")
    return errors, warnings
